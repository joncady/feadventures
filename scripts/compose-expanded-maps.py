"""Render expanded-only authored maps. Classic-four assets are never overwritten.
Chapter JSON layers use native source pixels enlarged exactly 2x; scene recipes
are approved complete architectural compositions, with no HUD or actor overlays.
"""
from pathlib import Path
import json
from PIL import Image
from map_art.approved_scenes import build_coast, build_ruins, ledger
ROOT=Path(__file__).resolve().parent.parent
OUT=ROOT/'public/assets/maps/expanded';OUT.mkdir(parents=True,exist_ok=True)
PROFILES=ROOT/'src/game/data/map-art/chapters'
profiles=[]
for path in sorted(PROFILES.glob('*.json')):
 p=json.loads(path.read_text());w,h=p['width'],p['height']
 if p.get('scene'):
  image,_=({'coast-rev6':build_coast,'shrine-rev7':build_ruins}[p['scene']])()
  image=image.resize((w,h),Image.Resampling.NEAREST)
 else:image=Image.new('RGBA',(w,h))
 for layer in p['layers']:
  source=Image.open(ROOT/layer['source']).convert('RGBA');x,y,cw,ch=layer['crop'];rx,ry,rw,rh=layer['rect'];scale=layer.get('scale',2)
  assert x>=0 and y>=0 and x+cw<=source.width and y+ch<=source.height,(path,layer)
  art=source.crop((x,y,x+cw,y+ch)).resize((cw*scale,ch*scale),Image.Resampling.NEAREST)
  assert layer['mode'] in ('stamp','tile')
  if layer['mode']=='stamp':
   assert (rw,rh)==art.size,(path,'stretched stamp',layer)
   image.alpha_composite(art,(rx,ry))
  else:
   for yy in range(ry,ry+rh,art.height):
    for xx in range(rx,rx+rw,art.width):image.alpha_composite(art.crop((0,0,min(art.width,rx+rw-xx),min(art.height,ry+rh-yy))),(xx,yy))
 for x,y,rw,rh in p['solids']:assert x>=0 and y>=0 and rw>0 and rh>0 and x+rw<=w and y+rh<=h,(path,'solid bounds')
 image.convert('RGB').save(OUT/(p['id']+'.png'))
 profiles.append(p)
 print(p['id'],image.size,'solids',len(p['solids']))
(ROOT/'src/game/data/map-art/generated.ts').write_text('// Generated by scripts/compose-expanded-maps.py. Edit chapter JSON, not this file.\nexport const AUTHORED_MAP_ART = '+json.dumps([{key:p[key] for key in ('id','width','height','identity','solids','anchors')} for p in profiles],indent=2)+' as const;\n')
(OUT/'source-crops.json').write_text(json.dumps(ledger,indent=2)+'\n')
